-- ============================================================================
--  智慧材料库数字化管理系统 · PostgreSQL 15 建表脚本
--  目标库必须是 PostgreSQL（jsonb 字段依赖 PG）
--  脚本可重复执行：IF NOT EXISTS + ON CONFLICT
-- ============================================================================

-- ---------------------------------------------------------------------------
-- 1. 材料类目（四级：大类 → 子类 → 品牌 → 型号）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS material_category (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id     BIGINT,
    code          VARCHAR(64)  NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    level         SMALLINT     NOT NULL DEFAULT 1,
    unit          VARCHAR(32)  DEFAULT '个',
    safe_stock    NUMERIC(14, 3) NOT NULL DEFAULT 0,
    sort_no       INTEGER      NOT NULL DEFAULT 0,
    extra         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    create_by     VARCHAR(64),
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),
    deleted       SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT fk_category_parent FOREIGN KEY (parent_id) REFERENCES material_category (id) ON DELETE SET NULL
);
COMMENT ON TABLE  material_category IS '材料类目树';
COMMENT ON COLUMN material_category.parent_id   IS '父级类目 id，顶级为 NULL';
COMMENT ON COLUMN material_category.safe_stock  IS '该类目的安全库存阈值';

CREATE INDEX IF NOT EXISTS idx_category_parent ON material_category (parent_id);

-- ---------------------------------------------------------------------------
-- 2. 材料台账
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS material_item (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id   BIGINT       NOT NULL,
    code          VARCHAR(64)  NOT NULL UNIQUE,
    brand         VARCHAR(128),
    model         VARCHAR(128),
    spec          VARCHAR(255),
    unit_price    NUMERIC(12, 2) NOT NULL DEFAULT 0,
    currency      VARCHAR(8)   NOT NULL DEFAULT 'CNY',
    unit          VARCHAR(32)  NOT NULL DEFAULT '个',
    safe_stock    NUMERIC(14, 3) NOT NULL DEFAULT 0,
    stock_qty     NUMERIC(14, 3) NOT NULL DEFAULT 0,
    specs         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    image_url     VARCHAR(512),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),
    deleted       SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT fk_item_category FOREIGN KEY (category_id) REFERENCES material_category (id),
    CONSTRAINT ck_item_price CHECK (unit_price >= 0),
    CONSTRAINT ck_item_stock CHECK (stock_qty >= 0)
);
COMMENT ON TABLE  material_item IS '材料台账（品牌 / 型号 / 规格 / 单价）';
COMMENT ON COLUMN material_item.unit_price IS '参考单价，领用出库时写入流水快照';
COMMENT ON COLUMN material_item.specs      IS 'JSONB 动态规格，例如 {"浓度":"AR","包装":"500mL"}';

CREATE INDEX IF NOT EXISTS idx_item_category ON material_item (category_id);

-- ---------------------------------------------------------------------------
-- 3. 库存批次（一物一码）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stock_batch (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT       NOT NULL,
    batch_code    VARCHAR(64)  NOT NULL UNIQUE,
    barcode       VARCHAR(128) NOT NULL UNIQUE,
    quantity      NUMERIC(14, 3) NOT NULL DEFAULT 0,
    initial_qty   NUMERIC(14, 3) NOT NULL DEFAULT 0,
    location      VARCHAR(64),
    expire_date   DATE,
    supplier      VARCHAR(128),
    inbound_time  TIMESTAMP    NOT NULL DEFAULT now(),
    status        VARCHAR(16)  NOT NULL DEFAULT 'IN_STOCK',
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),
    update_time   TIMESTAMP    NOT NULL DEFAULT now(),
    deleted       SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT fk_batch_item FOREIGN KEY (item_id) REFERENCES material_item (id),
    CONSTRAINT ck_batch_qty CHECK (quantity >= 0)
);
COMMENT ON TABLE  stock_batch IS '库存批次：批次号 + 条码，二维码标签指向本表 batch_code';
COMMENT ON COLUMN stock_batch.initial_qty IS '入库初始数量，用于出入库核对';

CREATE INDEX IF NOT EXISTS idx_batch_item ON stock_batch (item_id);
CREATE INDEX IF NOT EXISTS idx_batch_expire ON stock_batch (expire_date);

-- ---------------------------------------------------------------------------
-- 4. 出入库流水
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stock_transaction (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id      BIGINT       NOT NULL,
    item_id       BIGINT       NOT NULL,
    item_name     VARCHAR(255),
    txn_type      VARCHAR(16)  NOT NULL,
    qty           NUMERIC(14, 3) NOT NULL,
    unit_price    NUMERIC(12, 2) NOT NULL DEFAULT 0,
    amount        NUMERIC(14, 2) NOT NULL DEFAULT 0,
    user_id       BIGINT,
    user_name     VARCHAR(64),
    project_no    VARCHAR(64),
    usage_desc    TEXT,
    status        VARCHAR(16)  NOT NULL DEFAULT 'DONE',
    remark        VARCHAR(512),
    attachments   JSONB        NOT NULL DEFAULT '[]'::jsonb,
    extra         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    create_by     VARCHAR(64),
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT fk_txn_batch FOREIGN KEY (batch_id) REFERENCES stock_batch (id),
    CONSTRAINT fk_txn_item  FOREIGN KEY (item_id)  REFERENCES material_item (id),
    CONSTRAINT ck_txn_type  CHECK (txn_type IN ('IN', 'OUT', 'RETURN', 'SCRAP')),
    CONSTRAINT ck_txn_qty   CHECK (qty > 0)
);
COMMENT ON TABLE  stock_transaction IS '出入库流水：IN 入库 / OUT 领用 / RETURN 归还 / SCRAP 报废';
COMMENT ON COLUMN stock_transaction.txn_type   IS 'IN | OUT | RETURN | SCRAP';
COMMENT ON COLUMN stock_transaction.project_no IS '项目号 / 课程号，用于经费对应表';
COMMENT ON COLUMN stock_transaction.attachments IS 'JSONB 附件数组（报废照片等）';

CREATE INDEX IF NOT EXISTS idx_txn_batch ON stock_transaction (batch_id);
CREATE INDEX IF NOT EXISTS idx_txn_type_time ON stock_transaction (txn_type, create_time);
CREATE INDEX IF NOT EXISTS idx_txn_user_month ON stock_transaction (user_id, txn_type, create_time);

-- ---------------------------------------------------------------------------
-- 5. 系统用户（角色 + LDAP UID + 月度限额）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sys_user (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ldap_uid         VARCHAR(64)  NOT NULL UNIQUE,
    name             VARCHAR(64)  NOT NULL,
    role             VARCHAR(16)  NOT NULL DEFAULT 'student',
    password_hash    VARCHAR(128),
    email            VARCHAR(128),
    phone            VARCHAR(32),
    dept             VARCHAR(128),
    monthly_limit    NUMERIC(14, 3),
    status           VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    preferences      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    last_login_time  TIMESTAMP,
    create_time      TIMESTAMP    NOT NULL DEFAULT now(),
    update_time      TIMESTAMP    NOT NULL DEFAULT now(),
    deleted          SMALLINT     NOT NULL DEFAULT 0,
    CONSTRAINT ck_user_role CHECK (role IN ('guest', 'student', 'lab', 'teacher', 'buyer', 'admin'))
);
COMMENT ON TABLE  sys_user IS '系统用户：role 控制权限，ldap_uid 对接统一身份认证';
COMMENT ON COLUMN sys_user.monthly_limit IS '学生月度领用限额（单位随材料单位），NULL = 不限';

CREATE INDEX IF NOT EXISTS idx_user_role ON sys_user (role);

-- ---------------------------------------------------------------------------
-- 6. 库存预警记录（低于安全库存时写入）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stock_alert (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id       BIGINT       NOT NULL,
    item_name     VARCHAR(255),
    batch_id      BIGINT,
    current_qty   NUMERIC(14, 3) NOT NULL,
    safe_stock    NUMERIC(14, 3) NOT NULL,
    level         VARCHAR(16)  NOT NULL DEFAULT 'warning',
    status        VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    source_txn_id BIGINT,
    payload       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    notified_at   TIMESTAMP,
    closed_at     TIMESTAMP,
    create_time   TIMESTAMP    NOT NULL DEFAULT now(),
    CONSTRAINT fk_alert_item FOREIGN KEY (item_id) REFERENCES material_item (id),
    CONSTRAINT ck_alert_level CHECK (level IN ('warning', 'danger'))
);
COMMENT ON TABLE  stock_alert IS '安全库存预警记录';
COMMENT ON COLUMN stock_alert.level IS 'warning=低于安全库存 / danger=低于安全库存的 50%';

-- 同一材料同时只保留一条未关闭的预警
CREATE UNIQUE INDEX IF NOT EXISTS uk_alert_open_item
    ON stock_alert (item_id) WHERE status = 'OPEN';
CREATE INDEX IF NOT EXISTS idx_alert_status ON stock_alert (status, create_time);
